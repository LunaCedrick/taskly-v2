test('G3 offline local apply protects unload and keeps pending destructive confirmation disabled', async ({ page }) => {
  await signIn(page)
  await navigate(page, '/projects/project-empty')
  await network(page, false)
  await page.getByRole('button', { name: 'Quick Add', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title').fill('Pending G3 task')
  await dialog.getByLabel('Title').press('Enter')
  await expect(page.locator('[data-task-id]').filter({ hasText: 'Pending G3 task' })).toBeVisible()
  expect(await page.evaluate(() => {
    const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented
  })).toBe(true)
  await dialog.getByLabel('Title').press('Escape')
  await page.getByRole('button', { name: 'Delete project', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Delete project', exact: true })).toBeDisabled()
  await expect(dialog).toContainText('Waiting for pending task writes')
  await network(page, true)
  await expect(dialog.getByRole('button', { name: 'Delete project', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await page.evaluate(() => {
    const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented
  })).toBe(false)
})

test('G3 cascades more than 1,000 tasks with one project summary while dismissed', async ({ page }) => {
  const uid = await signIn(page, '/', { seed: false })
  await seedUser(uid, { taskCount: 3003 })
  await waitForSync(page, { tasks: 3003 })
  await navigate(page, '/projects/project-1')
  await page.getByRole('button', { name: 'Delete project', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('1001 tasks')
  await dialog.getByRole('button', { name: 'Delete project', exact: true }).click()
  await page.keyboard.press('Escape')
  // Completion is a sync condition, not an unapproved five-second cascade latency gate.
  await waitForSync(page, { projects: 3, tasks: 2002 })
  const state = await writeSnapshot(page)
  expect(state.activity.filter((event) => event.type === 'project.deleted')).toHaveLength(1)
  expect(state.activity.some((event) => event.type === 'task.deleted')).toBe(false)
  await expect(page).toHaveURL('/')
})

test('G3 project movement is live only in the project route and preserves listener registrations', async ({ page }) => {
  await signIn(page)
  await navigate(page, '/projects/project-1')
  const task = (await writeSnapshot(page)).tasks.find((item) => item.id === 'task-1')!
  await page.getByRole('button', { name: `Edit ${task.title}`, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Project', exact: true }).selectOption('project-2')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect.poll(async () => (await writeSnapshot(page)).tasks.find((item) => item.id === 'task-1')?.projectId).toBe('project-2')
  expect((await writeSnapshot(page)).activity.some((event) => event.type === 'task.project_moved')).toBe(true)
  await navigate(page, '/tasks')
  await expect(page.locator('[data-row-action]')).toHaveCount(0)
  expect(await page.evaluate(() => window.__TASKLY_G2_SYNC_TEST__!.snapshot().activeHandles)).toBe(3)
})
